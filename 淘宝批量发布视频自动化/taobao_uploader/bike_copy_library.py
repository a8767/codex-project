def seed_bike_video_copies(connection: sqlite3.Connection) -> int:
    connection.execute("""CREATE TABLE IF NOT EXISTS bike_video_copies (
        copy_id TEXT PRIMARY KEY,
        direction TEXT NOT NULL,
        video_theme TEXT NOT NULL,
        title TEXT NOT NULL CHECK(length(title) <= 30),
        body TEXT NOT NULL,
        usage_scenario TEXT NOT NULL
    )""")
    connection.executemany(
        "INSERT OR IGNORE INTO bike_video_copies VALUES(?,?,?,?,?,?)",
        ((f"bike-{index:02d}", *item) for index, item in enumerate(BIKE_VIDEO_COPIES, 1)),
    )
    connection.commit()
    return connection.execute("SELECT count(*) FROM bike_video_copies").fetchone()[0]
